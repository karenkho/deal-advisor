"""The BRD as a Word document in the Exist structure (Appendix A), and the parser for an edited file coming back. Rendered from a
version's snapshot, so any version can be reopened. The database stays authoritative: re-upload shows a diff and changes nothing
until it is confirmed. No hours, costs or rates are in here."""
