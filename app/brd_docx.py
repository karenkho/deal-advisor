FOOTER = "Generated by Deal Advisor. The application record is authoritative. To change requirements, edit this file and re-upload it in Deal Advisor."
PURPOSE = "This document records the business requirements of the initiative, as understood at presales, for validation before estimation."
BR_ID_HEADER = "BR ID (do not edit)"
BR_COLUMNS = (BR_ID_HEADER, "Epic", "Title", "Requirement Statement", "Priority", "Complexity", "Rationale", "Source", "Notes")
STATUS_LABEL = {"Draft": "Draft", "Under validation": "For Review", "Approved": "Approved", "Superseded": "Obsolete"}
WATERMARK = {"Draft": "DRAFT", "Under validation": "DRAFT", "Approved": "APPROVED", "Superseded": "SUPERSEDED"}
_ID_PATTERNS = {"objective": r"BO-\d+", "in_scope": r"IS-\d+", "out_of_scope": r"OOS-\d+", "risk": r"R-\d+"}
_DATE_SUFFIX = re.compile(r",\s*\d{4}-\d{2}-\d{2}$")
_SECTION_NUMBER = re.compile(r"^(\d+(?:\.\d+)*)")
MAX_PLACES = 4
NEEDS_REWORDING = "Needs rewording"
_SPLIT = re.compile(r"split from\s+(BR-\d+)", re.I)
_MERGED = re.compile(r"merged into\s+(BR-\d+)", re.I)


QUESTIONS = "open_question"
SECTION_LABEL = {"objective": "Objective", "in_scope": "In scope", "out_of_scope": "Out of scope", "risk": "Risk", QUESTIONS: "Open question"}


class BrdFileError(Exception):
    """The file cannot be applied; nothing was changed."""


def file_name(code: str, label: str) -> str:
    return f"BRD-{code}-R1-v{label}.docx"


def document_id(code: str) -> str:
    return f"BRD-{code}-R1"


def _table(doc, headers: tuple, rows: list[tuple]) -> None:
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        cell = table.rows[0].cells[i]
        cell.text = ""
        run = cell.paragraphs[0].add_run(h)
        run.bold = True
    for row in rows:
        cells = table.add_row().cells
        for i, value in enumerate(row):
            cells[i].text = "" if value is None else str(value)
    doc.add_paragraph()


def _page_field(paragraph) -> None:
    run = paragraph.add_run()
    for kind, text in (("begin", None), (None, "PAGE"), ("end", None)):
        if kind:
            el = OxmlElement("w:fldChar")
            el.set(qn("w:fldCharType"), kind)
        else:
            el = OxmlElement("w:instrText")
            el.text = text
        run._r.append(el)


def _source(citations: list[dict]) -> str:
    """Per document: "TOR §3.2, §5.3; Bid Bulletin No. 01 §2.1". An amending document is never cut off by a long TOR list."""
    by_doc: dict[str, list[str]] = {}
    for c in citations:
        doc = _DATE_SUFFIX.sub("", c.get("doc_label") or "TOR")
        number = _SECTION_NUMBER.match(c.get("section") or "")
        place = f"§{number.group(1)}" if number else f"p.{c['page']}" if c.get("page") else ""
        places = by_doc.setdefault(doc, [])
        if place and place not in places:
            places.append(place)
    if not by_doc:
        return "Inferred, not stated in the documents"
    def join(places: list[str]) -> str:
        return ", ".join(places[:MAX_PLACES]) + (f" (+{len(places) - MAX_PLACES})" if len(places) > MAX_PLACES else "")
    return "; ".join(f"{doc} {join(places)}".strip() for doc, places in by_doc.items())


def _items(snapshot: dict, section: str) -> list[dict]:
    return sorted((i for i in snapshot["section_items"] if i["section"] == section), key=lambda i: i["sort_order"])


def render(session: Session, opp_id: str, version: models.ArtifactVersion | None = None) -> bytes:
    version = version or opportunities.current_version(session, opp_id, "BRD")
    opp = session.get(models.Opportunity, opp_id)
    # the revision history and approvals are printed in the document, so they are part of what it is built from
    approvals = [(a.approver_name, a.decision, a.stage) for a in _approvals_of(session, opp_id, version)]
    key = doc_cache.digest("brd", doc_cache.version_hash(version), doc_cache.opportunity_hash(opp), _revisions(session, opp_id, version), approvals)
    return doc_cache.remember(key, lambda: _render(session, opp_id, version, opp))


def _render(session: Session, opp_id: str, version: models.ArtifactVersion, opp: models.Opportunity) -> bytes:
    snap = version.snapshot
    label = version.version_label
    doc = Document()
    doc.styles["Normal"].font.name = "Calibri"
    doc.styles["Normal"].font.size = Pt(10)
    section = doc.sections[0]
    mark = section.header.paragraphs[0].add_run(f"{WATERMARK[version.status]} · {document_id(opp.code)} · v{label}")
    mark.bold = True
    mark.font.color.rgb = RGBColor(0x99, 0x33, 0x33) if version.status != "Approved" else RGBColor(0x2E, 0x6B, 0x3A)
    foot = section.footer.paragraphs[0]
    foot.add_run(FOOTER + " Page ").font.size = Pt(8)
    _page_field(foot)

    doc.add_heading("Business Requirements Document", 0)
    doc.add_heading("Document Information", 1)
    bdm = opp.bdm_name or TO_CONFIRM
    _table(doc, ("Field", "Value"), [
        ("Document ID", document_id(opp.code)), ("Version", label), ("Date", version.created_at.date().isoformat()), ("Project / Initiative", opp.name), ("Business Owner", opp.client_name),
        ("Prepared By", f"{version.created_by} – {version.created_role}"), ("Confidentiality", "Internal"), ("Document Status", STATUS_LABEL[version.status]), ("Document Owner", bdm),
        ("Required Approvers", "Solutions Specialist; BDM informed"), ("Controlled File Name", file_name(opp.code, label))])
    doc.add_heading("Purpose", 1)
    doc.add_paragraph(PURPOSE)
    doc.add_heading("Revision History", 1)
    _table(doc, ("Version", "Date", "Author", "Change Summary", "Reviewed By", "Approved By"), _revisions(session, opp_id, version))
    doc.add_heading("Stakeholders", 1)
    approvals = _approvals_of(session, opp_id, version)
    specialist = next((a.approver_name for a in approvals), TO_CONFIRM)
    _table(doc, ("Role", "Name", "Responsibility"), [("Client Business Owner", opp.client_name, "Owns the business requirements"), ("BDM", bdm, "Commercial owner of the opportunity"),
                                                     ("Solutions Specialist", specialist, "Validates and approves the requirements"), ("Prepared by", "Deal Advisor, AI draft", "Generates the draft for validation")])

    doc.add_heading("1. Executive Summary", 1)
    _table(doc, ("Section", "Details"), [(i["data"]["section"], i["data"]["details"]) for i in _items(snap, "executive_summary")] or [("Summary", NOT_STATED)])
    doc.add_heading("2. Business Objectives and Success Metrics", 1)
    _table(doc, ("Objective ID", "Objective", "KPI / Metric", "Baseline", "Target", "Measurement Method"),
           [(i["item_id"], i["data"]["objective"], i["data"]["kpi"], i["data"]["baseline"], i["data"]["target"], i["data"]["measurement"]) for i in _items(snap, "objective")])
    doc.add_heading("3. Scope", 1)
    doc.add_heading("3.1 In Scope", 2)
    _table(doc, ("ID", "Capability / Process", "Description"), [(i["item_id"], i["data"]["capability"], i["data"]["description"]) for i in _items(snap, "in_scope")])
    doc.add_heading("3.2 Out of Scope", 2)
    _table(doc, ("ID", "Exclusion", "Rationale"), [(i["item_id"], i["data"]["exclusion"], i["data"]["rationale"]) for i in _items(snap, "out_of_scope")])
    doc.add_heading("4. Business Process Overview", 1)
    doc.add_heading("4.1 Current State (As-Is)", 2)
    _table(doc, ("Process", "Description", "Pain Points"), [(i["data"]["process"], i["data"]["description"], i["data"]["pain_points"]) for i in _items(snap, "process_as_is")] or [(NOT_DESCRIBED, "", "")])
    doc.add_heading("4.2 Future State (To-Be)", 2)
    _table(doc, ("Process", "Description", "Improvement"), [(i["data"]["process"], i["data"]["description"], i["data"]["improvement"]) for i in _items(snap, "process_to_be")] or [(NOT_DESCRIBED, "", "")])

    doc.add_heading("5. Business Requirements", 1)
    _requirements_table(doc, snap)
    doc.add_heading("6. Business Rules", 1)
    _table(doc, ("Rule ID", "Rule Description", "Owner", "Compliance / Policy Reference", "Related BR IDs"),
           [(r["item_id"], r["text"], r["owner"] or TO_CONFIRM, r["policy_reference"] or NOT_STATED, ", ".join(r["br_ids"])) for r in snap["business_rules"]])
    doc.add_heading("7. Data and Reporting Requirements", 1)
    _table(doc, ("Area", "Requirement", "Frequency", "Owner"), [(i["data"]["area"], i["data"]["requirement"], i["data"]["frequency"], i["data"]["owner"]) for i in _items(snap, "data_reporting")])
    doc.add_heading("8. Non-Functional Business Expectations", 1)
    _table(doc, ("Category", "Expectation", "Metric / Target", "Notes"),
           [(n["category"] or "Other", n["text"], n["metric_target"] or NOT_STATED, "" if n["measurable"] is not False else "Not measurable as written") for n in snap["nfrs"]])
    doc.add_heading("9. Assumptions, Dependencies, and Constraints", 1)
    _table(doc, ("Type", "Description", "Impact", "Owner", "Status"),
           [(c["item_type"], c["text"], c["impact"] or "Med", c["owner"] or TO_CONFIRM, c["status"]) for c in snap["constraints_assumptions"]])
    doc.add_heading("10. Risks and Mitigations", 1)
    _table(doc, ("Risk ID", "Risk Description", "Probability", "Impact", "Mitigation", "Owner"),
           [(i["item_id"], i["data"]["description"], i["data"]["probability"], i["data"]["impact"], i["data"]["mitigation"], i["data"]["owner"]) for i in _items(snap, "risk")])
    doc.add_heading("11. Open Questions and Clarifications", 1)
    _table(doc, ("Question ID", "Question", "Related BR IDs", "Blocking", "Status", "Answer Source"),
           [(q["item_id"], q["text"], ", ".join(q["br_ids"]), "Yes" if q["blocking"] else "No", q["status"], q["answer_source"] or "") for q in snap["open_questions"]])
    doc.add_heading("12. Approval and Sign-off", 1)
    rows = [("Solutions Specialist", a.approver_name, a.decision, a.decided_at.date().isoformat(), a.comment or "") for a in approvals] or [("Solutions Specialist", "", "Pending", "", "")]
    _table(doc, ("Role", "Name", "Decision", "Date", "Remarks"), rows + [("BDM", bdm, "Acknowledged" if approvals else "Pending", "", "")])
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


def _requirements_table(doc, snap: dict) -> None:
    table = doc.add_table(rows=1, cols=len(BR_COLUMNS))
    table.style = "Table Grid"
    for i, h in enumerate(BR_COLUMNS):
        table.rows[0].cells[i].text = ""
        table.rows[0].cells[i].paragraphs[0].add_run(h).bold = True
    active = [b for b in snap["brs"] if b["lifecycle_status"] == "Active"]
    for epic in snap["epics"]:
        rows = sorted((b for b in active if b["epic_id"] == epic["epic_id"]), key=lambda b: (b["sort_order"], b["br_id"]))
        if not rows:
            continue
        head = table.add_row().cells
        merged = head[0].merge(head[-1])
        merged.text = ""
        merged.paragraphs[0].add_run(f"{epic['epic_id']} {epic['name']}").bold = True
        for b in rows:
            cells = table.add_row().cells
            values = (b["br_id"], b["epic_id"], b["title"], b["statement"], b["priority"], b["complexity"] or "", b["rationale"] or "", _source(b["source_citations"]), NEEDS_REWORDING if b["ext"].get("needs_rewording") else "")
            for i, value in enumerate(values):
                cells[i].text = value
    doc.add_paragraph()


def _approvals_of(session: Session, opp_id: str, version: models.ArtifactVersion) -> list[models.Approval]:
    return session.scalars(select(models.Approval).where(models.Approval.opportunity_id == opp_id, models.Approval.artifact_version_id == version.id)).all()


def _revisions(session: Session, opp_id: str, upto: models.ArtifactVersion) -> list[tuple]:
    rows = []
    versions = session.scalars(select(models.ArtifactVersion).where(models.ArtifactVersion.opportunity_id == opp_id, models.ArtifactVersion.artifact_type == "BRD")
                               .order_by(models.ArtifactVersion.version_major, models.ArtifactVersion.version_minor)).all()
    for v in versions:
        if (v.version_major, v.version_minor) > (upto.version_major, upto.version_minor):
            break
        approved = ", ".join(a.approver_name for a in _approvals_of(session, opp_id, v))
        rows.append((v.version_label, v.created_at.date().isoformat(), v.created_by, v.change_summary or "", approved, approved))
    return rows


def leak_hits(data: bytes, rates: costing.RateTable | None = None) -> list[dict]:
    """The guardrail, before any download: internal terms and rate values must not appear. A BRD holds no hours of ours, so
    hours the TOR states (e.g. a response time) are allowed."""
    blocked = {"rate": set(), "cost": set(), "percent": set(), "factor": set(), "hours": set()}
    for table in [costing.illustrative_rates()] + ([rates] if rates else []):
        for value in list(table.published.values()) + list(table.applied(0.0).values()):
            blocked["rate"] |= leak._forms(value)
    return leak.scan(data, blocked, document="BRD")


