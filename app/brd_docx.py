def _cell(cell) -> str:
    return " ".join(cell.text.split())


def _doc_sections(doc) -> dict[str, list[str]]:
    """Heading -> lines, tables as pipe-joined rows, in document order."""
    out: dict[str, list[str]] = {}
    current = "Front matter"
    for el in doc.element.body.iterchildren():
        if el.tag == qn("w:p"):
            text = "".join(t.text or "" for t in el.iter(qn("w:t"))).strip()
            style = el.find(qn("w:pPr"))
            name = style.find(qn("w:pStyle")).get(qn("w:val")) if style is not None and style.find(qn("w:pStyle")) is not None else ""
            if name.lower().startswith("heading") and text:
                current = text
            elif text:
                out.setdefault(current, []).append(text)
        elif el.tag == qn("w:tbl"):
            for tr in el.iter(qn("w:tr")):
                cells = ["".join(t.text or "" for t in tc.iter(qn("w:t"))).strip() for tc in tr.findall(qn("w:tc"))]
                out.setdefault(current, []).append(" | ".join(cells))
    return out


def parse(data: bytes) -> dict:
    """Reads an edited BRD file. Raises BrdFileError for anything that is not one of ours."""
    try:
        doc = Document(io.BytesIO(data))
    except Exception as e:  # noqa: BLE001 — any unreadable file
        raise BrdFileError("This is not a readable Word document.") from e
    info = {}
    table = None
    tables = {}
    for t in doc.tables:
        header = [_cell(c) for c in t.rows[0].cells]
        if header[:2] == ["Field", "Value"]:
            info = {_cell(r.cells[0]): _cell(r.cells[1]) for r in t.rows[1:]}
        elif BR_ID_HEADER in header:
            table = t
        tables[header[0]] = t
    if table is None:
        raise BrdFileError(f"The Business Requirements table was not found: no “{BR_ID_HEADER}” column. Download the BRD from Deal Advisor and edit that file.")
    header = [_cell(c) for c in table.rows[0].cells]
    missing = [c for c in ("Title", "Requirement Statement", "Priority") if c not in header]
    if missing:
        raise BrdFileError(f"The Business Requirements table has lost its columns: {', '.join(missing)}. Nothing was changed.")
    rows, epic = [], None
    for tr in table.rows[1:]:
        values = dict(zip(header, (_cell(c) for c in tr.cells)))
        cells = list(values.values())
        if cells and len(set(cells)) == 1 and re.match(r"^EP-\d+\b", cells[0]):
            epic = cells[0].split()[0]
            continue
        if not any(cells):
            continue
        rows.append({"br_id": values.get(BR_ID_HEADER, ""), "epic_id": values.get("Epic") or epic, "title": values.get("Title", ""), "statement": values.get("Requirement Statement", ""),
                     "priority": values.get("Priority", ""), "complexity": values.get("Complexity", "").lower(), "rationale": values.get("Rationale", ""), "notes": values.get("Notes", "")})
    # one list per table: a row as it stands in the file, so a repeated or emptied ID can be told apart from a removed one
    items = {section: [] for section in _ID_PATTERNS}
    found = set()

    def read(section: str, t, keys: tuple) -> None:
        found.add(section)
        for tr in t.rows[1:]:
            cells = [_cell(c) for c in tr.cells]
            items[section].append({"file_id": cells[0], "data": dict(zip(keys, cells[1:]))})

    if "Objective ID" in tables:
        read("objective", tables["Objective ID"], ("objective", "kpi", "baseline", "target", "measurement"))
    for t in (t for t in doc.tables if _cell(t.rows[0].cells[0]) == "ID"):
        if _cell(t.rows[0].cells[1]).startswith("Capability"):
            read("in_scope", t, ("capability", "description"))
        else:
            read("out_of_scope", t, ("exclusion", "rationale"))
    if "Risk ID" in tables:
        read("risk", tables["Risk ID"], ("description", "probability", "impact", "mitigation", "owner"))
    questions = []
    if "Question ID" in tables:
        found.add(QUESTIONS)
        for tr in tables["Question ID"].rows[1:]:
            cells = [_cell(c) for c in tr.cells]
            questions.append({"file_id": cells[0], "data": {"text": cells[1], "status": cells[4], "answer_source": cells[5]}})
    return {"document_id": info.get("Document ID", ""), "version": info.get("Version", ""), "rows": rows, "items": items, "questions": questions, "found": found, "sections": _doc_sections(doc)}


def _clean(value: str | None) -> str:
    return " ".join((value or "").split())


@tracing.traced("brd_reupload_diff", lambda session, opp_id, data, *a, **k: {"opportunity_id": opp_id, "document_bytes": len(data)}, tracing.shape, "chain")
def diff(session: Session, opp_id: str, data: bytes, parents: dict[int, str] | None = None) -> dict:
    """{"changes", "text_diffs", "impact", "unlinked", "renumbered"}: what applying this file would do. parents: new row index -> the BR it was
    split from, chosen by the user for rows that do not say. Raises BrdFileError; nothing is changed either way."""
    parsed = parse(data)
    opp = session.get(models.Opportunity, opp_id)
    current = opportunities.current_version(session, opp_id, "BRD")
    if parsed["document_id"] != document_id(opp.code):
        raise BrdFileError(f"This file belongs to {parsed['document_id'] or 'another document'}, not {document_id(opp.code)}. Nothing was changed.")
    if parsed["version"] != current.version_label:
        raise BrdFileError(f"This file is v{parsed['version']}, but the BRD is now v{current.version_label}. Download the latest version and redo the edit. Nothing was changed.")

    brs = brd_service.all_brs(session, opp_id)
    epics = {e.epic_id for e in session.scalars(select(models.Epic).where(models.Epic.opportunity_id == opp_id))}
    active = {b.br_id for b in brs.values() if b.lifecycle_status == "Active"}
    problems, seen = [], set()
    for row in parsed["rows"]:
        bid = row["br_id"]
        where = bid or f"the new row “{row['title'][:40]}”"
        if bid:
            if bid in seen:
                problems.append(f"{bid} appears twice.")
            elif bid not in active:
                problems.append(f"{bid} is not a current BR ID. IDs must not be edited.")
            seen.add(bid)
        if row["priority"] not in brd_service.PRIORITIES:
            problems.append(f"{where}: priority must be Must, Should or Could.")
        if row["complexity"] and row["complexity"] not in brd_service.COMPLEXITIES:
            problems.append(f"{where}: complexity must be low, medium or high.")
        if row["epic_id"] not in epics:
            problems.append(f"{where}: unknown epic {row['epic_id']}.")
        if not (row["title"] and row["statement"]):
            problems.append(f"{where}: title and statement are required.")
        for rx in (_SPLIT, _MERGED):
            m = rx.search(row["notes"])
            if m and m.group(1) not in active:
                problems.append(f"{where}: {m.group(1)} in Notes is not a current BR ID.")
    if problems:
        raise BrdFileError("Nothing was changed. " + " ".join(problems))

    changes = brd_service.empty_changes()
    impact, new_rows = [], []
    merged_away = set()
    for row in parsed["rows"]:
        if row["br_id"]:
            m = _MERGED.search(row["notes"])
            if m:
                changes["merged"].append({"br_id": row["br_id"], "into": m.group(1)})
                merged_away.add(row["br_id"])
                continue
            br = brs[row["br_id"]]
            edits = {}
            for field, value in (("title", row["title"]), ("statement", row["statement"]), ("priority", row["priority"]), ("complexity", row["complexity"] or None),
                                 ("rationale", row["rationale"] or None), ("epic_id", row["epic_id"])):
                if _clean(getattr(br, field)) != _clean(value):
                    edits[field] = value
            if edits:
                changes["modified"].append({"br_id": br.br_id, "changes": edits})
                new_size = brd_service.resize(br.size, br.statement, edits["statement"]) if "statement" in edits else br.size
                impact.append({"br_id": br.br_id, "change": "modified", "size_from": br.size, "size_to": new_size})
        else:
            new_rows.append(row)
    unlinked = []
    split_parents = set()
    kept = {r["br_id"] for r in parsed["rows"] if r["br_id"]}
    for i, row in enumerate(new_rows):
        m = _SPLIT.search(row["notes"])
        parent = m.group(1) if m else (parents or {}).get(i)
        if parent:
            split_parents.add(parent)
        elif not (parents and i in parents) and (active - kept):
            unlinked.append({"index": i, "title": row["title"]})
        entry = {"title": row["title"], "statement": row["statement"], "priority": row["priority"], "complexity": row["complexity"] or None, "rationale": row["rationale"] or None,
                 "epic_id": row["epic_id"], "split_from": parent, "retire_parent": bool(parent and parent not in kept)}
        changes["new"].append(entry)
        impact.append({"br_id": "new", "title": row["title"], "change": "split" if parent else "new", "size_from": None, "size_to": brd_service.rule_size(row["statement"])})
    changes["removed"] = sorted(active - kept - split_parents)
    impact += [{"br_id": b, "change": "removed", "size_from": brs[b].size, "size_to": None} for b in changes["removed"]]
    impact += [{"br_id": b, "change": "split", "size_from": brs[b].size, "size_to": None} for b in sorted(split_parents - kept)]
    impact += [{"br_id": m["br_id"], "change": f"merged into {m['into']}", "size_from": brs[m["br_id"]].size, "size_to": None} for m in changes["merged"]]

    # display order: only epics whose order really changed
    placeholders = {id(r): f"new:{i}" for i, r in enumerate(new_rows)}
    grouped: dict[str, list[str]] = {}
    for row in parsed["rows"]:
        if row["br_id"] not in merged_away:
            grouped.setdefault(row["epic_id"], []).append(row["br_id"] or placeholders[id(row)])
    for epic_id, refs in grouped.items():
        was = [b.br_id for b in sorted((x for x in brs.values() if x.epic_id == epic_id and x.lifecycle_status == "Active"), key=lambda x: (x.sort_order, x.br_id))]
        extras = [r for r in refs if r not in was]
        same_order = [r for r in refs if r in was] == [w for w in was if w in refs]
        appended = all(r.startswith("new:") for r in extras) and (not extras or refs[-len(extras):] == extras)
        if not (same_order and appended):
            changes["order"][epic_id] = refs

    renumbered = _section_changes(session, opp_id, parsed, changes)
    return {"changes": changes, "impact": impact, "unlinked": unlinked, "renumbered": renumbered, "text_diffs": _text_diffs(session, opp_id, current, parsed, changes, renumbered)}


def _match_rows(label: str, rows: list[dict], key: str, live: dict[str, str], withdrawn: set[str]) -> tuple[list[tuple[str, dict]], list[dict]]:
    """Which stored row each row of the file is. Word and Docs users renumber after deleting rows, so a row whose text is exactly another
    item's is that item, whatever ID it now carries. Returns ([(item id, row)], [{file_id, item_id}]). Anything still unclear is refused."""
    rows = [r for r in rows if r["file_id"] and _clean(r["data"][key])]     # a row emptied of its text counts as removed
    ids = [r["file_id"] for r in rows]
    repeated = sorted({i for i in ids if ids.count(i) > 1})
    if repeated:
        raise BrdFileError(f"{', '.join(repeated)} appears twice in {label}. Nothing was changed.")
    claimed: dict[str, dict] = {r["file_id"]: r for r in rows if _clean(live.get(r["file_id"])) == _clean(r["data"][key])}
    renumbered = []
    for row in rows:
        if row["file_id"] in claimed and claimed[row["file_id"]] is row:
            continue
        same = [i for i, text in live.items() if _clean(text) == _clean(row["data"][key]) and i not in claimed]
        if same:
            claimed[same[0]] = row
            renumbered.append({"file_id": row["file_id"], "item_id": same[0]})
    placed = {id(r) for r in claimed.values()}
    for row in rows:
        if id(row) in placed:
            continue
        item_id = row["file_id"]
        if item_id not in live and item_id not in withdrawn:
            raise BrdFileError(f"{item_id} is not a current ID in this BRD. IDs must not be edited. Nothing was changed.")
        if item_id in claimed:
            raise BrdFileError(f"{item_id} in {label}: its ID now belongs to another row and its text matches none. Download the BRD again and edit the text without renumbering. Nothing was changed.")
        claimed[item_id] = row
    return list(claimed.items()), renumbered


def _section_changes(session: Session, opp_id: str, parsed: dict, changes: dict) -> list[dict]:
    """Objectives, scope, risks and open questions, by ID: an edited row is a change, a row no longer in the file is a withdrawal to confirm, and a
    withdrawn ID typed back in is a reinstatement. Everything else is shown as a text diff only. Returns the rows found renumbered."""
    stored = session.scalars(select(models.BrdSectionItem).where(models.BrdSectionItem.opportunity_id == opp_id)).all()
    prefix = {"objective": "BO", "in_scope": "IS", "out_of_scope": "OOS", "risk": "R"}
    out = []
    for section, rows in parsed["items"].items():
        key = store.ITEM_TEXT[section]
        here = {i.item_id: i for i in stored if i.section == section}
        live = {k: str(i.data.get(key, "")) for k, i in here.items() if not i.withdrawn}
        if section not in parsed["found"]:
            if live:
                raise BrdFileError(f"The {SECTION_LABEL[section]} table is missing from this file. To remove its rows, delete the rows and keep the table. Nothing was changed.")
            continue
        for row in rows:
            if not row["file_id"] and any(row["data"].values()):
                changes["sections"].append({"section": section, "prefix": prefix[section], "data": row["data"]})
        matched, renumbered = _match_rows(SECTION_LABEL[section], rows, key, live, {k for k, i in here.items() if i.withdrawn})
        out += renumbered
        for item_id, row in matched:
            if item_id not in live and item_id not in here:
                raise BrdFileError(f"{item_id} is not a current ID in this BRD. IDs must not be edited. Nothing was changed.")
            current = here[item_id]
            if current.withdrawn:
                changes["reinstated"].append({"section": section, "item_id": item_id, "text": row["data"][key]})
            merged = {**current.data, **row["data"]}
            if {k: _clean(str(v)) for k, v in merged.items()} != {k: _clean(str(v)) for k, v in current.data.items()}:
                changes["sections"].append({"section": section, "item_id": item_id, "data": merged})
        kept = {item_id for item_id, _ in matched}
        changes["withdrawn"] += [{"section": section, "item_id": k, "text": text} for k, text in sorted(live.items()) if k not in kept]
    questions = {q.item_id: q for q in session.scalars(select(models.OpenQuestion).where(models.OpenQuestion.opportunity_id == opp_id))}
    live = {k: q.text for k, q in questions.items() if not q.withdrawn}
    if QUESTIONS not in parsed["found"]:
        if live:
            raise BrdFileError("The Open Questions table is missing from this file. To remove questions, delete their rows and keep the table. Nothing was changed.")
        return out
    if any(not r["file_id"] and r["data"]["text"] for r in parsed["questions"]):
        raise BrdFileError("A question row has no ID. New open questions cannot be added from a file. Nothing was changed.")
    matched, renumbered = _match_rows(SECTION_LABEL[QUESTIONS], parsed["questions"], "text", live, {k for k, q in questions.items() if q.withdrawn})
    out += renumbered
    for item_id, row in matched:
        q = questions[item_id]
        data = row["data"]
        if q.withdrawn:
            changes["reinstated"].append({"section": QUESTIONS, "item_id": item_id, "text": data["text"]})
            data = {**data, "status": q.withdrawn.get("previous_status", "Open")}
        edits = {k: v for k, v in data.items() if _clean(getattr(q, k)) != _clean(v) and not (q.withdrawn and k == "status")}
        if edits:
            changes["questions"].append({"item_id": item_id, **edits})
    kept = {item_id for item_id, _ in matched}
    changes["withdrawn"] += [{"section": QUESTIONS, "item_id": k, "text": text} for k, text in sorted(live.items()) if k not in kept]
    return out


_STRUCTURED = re.compile(r"^(5\. Business Requirements|Document Information|Revision History|Stakeholders)")


def _text_diffs(session: Session, opp_id: str, current: models.ArtifactVersion, parsed: dict, changes: dict, renumbered: list[dict]) -> list[dict]:
    """What the file changed that cannot be applied. A row already handled by ID is not repeated here as if it were ignored."""
    was = _doc_sections(Document(io.BytesIO(render(session, opp_id, current))))
    now = parsed["sections"]
    handled = {x["item_id"] for x in changes["withdrawn"] + changes["reinstated"] + changes["questions"]} | {x["item_id"] for x in changes["sections"] if x.get("item_id")} | {x for r in renumbered for x in r.values()}
    out = []
    for heading in list(dict.fromkeys(list(was) + list(now))):
        if _STRUCTURED.match(heading):
            continue
        a, b = was.get(heading, []), now.get(heading, [])
        if [_clean(x) for x in a] != [_clean(x) for x in b]:
            lines = [line for line in difflib.ndiff(a, b) if line[:1] in "+-" and line[2:].split(" | ")[0].strip() not in handled]
            if lines:
                out.append({"section": heading, "diff": lines})
    return out
